/**
 * Build step: content/guides/{ar,en}/*.md  ->  src/generated/guides.js
 * Runs automatically before `wrangler deploy` (wrangler.toml [build]) and before `npm test`.
 * Files starting with "_" (like _TEMPLATE.md) are ignored. A guide with problems fails the build
 * with a message that says exactly what to fix.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFrontMatter, readingMinutes, renderMarkdown } from '../src/lib/markdown.js';
import { AFFILIATES } from '../src/config.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'content', 'guides');
const outFile = join(root, 'src', 'generated', 'guides.js');

const REQUIRED = ['title', 'description', 'date', 'author'];
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DATE_RE = /^\d{4}-\d{2}-\d{2}$/;

export function buildGuides(dir = contentDir) {
  const guides = [];
  const errors = [];

  for (const lang of ['ar', 'en']) {
    const langDir = join(dir, lang);
    if (!existsSync(langDir)) continue;
    for (const file of readdirSync(langDir).sort()) {
      if (!file.endsWith('.md') || file.startsWith('_')) continue;
      const where = `content/guides/${lang}/${file}`;
      const slug = file.replace(/\.md$/, '');
      const { data, body } = parseFrontMatter(readFileSync(join(langDir, file), 'utf8'));

      if (!SLUG_RE.test(slug)) errors.push(`${where}: file name must be lowercase-latin-with-dashes (it becomes the URL)`);
      for (const key of REQUIRED) if (!data[key]) errors.push(`${where}: missing "${key}" in the front matter`);
      for (const key of ['date', 'updated']) {
        if (data[key] && !DATE_RE.test(String(data[key]))) errors.push(`${where}: "${key}" must look like 2026-11-03`);
      }
      const affiliates = Array.isArray(data.affiliates) ? data.affiliates : [];
      for (const id of affiliates) {
        if (!AFFILIATES.some((a) => a.id === id)) errors.push(`${where}: unknown affiliate "${id}" (see AFFILIATES in src/config.js)`);
      }
      if (body.trim().split(/\s+/).length < 300 && data.draft !== true) {
        errors.push(`${where}: under 300 words - finish it or set "draft: true"`);
      }

      const { html, headings } = renderMarkdown(body);
      guides.push({
        lang,
        slug,
        title: String(data.title || ''),
        description: String(data.description || ''),
        date: String(data.date || ''),
        updated: String(data.updated || data.date || ''),
        author: String(data.author || ''),
        translation: data.translation ? String(data.translation) : '',
        affiliates,
        draft: data.draft === true,
        minutes: readingMinutes(body),
        headings,
        html,
      });
    }
  }

  for (const g of guides) {
    if (!g.translation) continue;
    const other = g.lang === 'ar' ? 'en' : 'ar';
    if (!guides.some((x) => x.lang === other && x.slug === g.translation)) {
      errors.push(`content/guides/${g.lang}/${g.slug}.md: translation "${g.translation}" not found in content/guides/${other}/`);
    }
  }
  return { guides, errors };
}

function main() {
  const { guides, errors } = buildGuides();
  if (errors.length) {
    console.error(`Guide build failed:\n  - ${errors.join('\n  - ')}`);
    process.exit(1);
  }
  mkdirSync(dirname(outFile), { recursive: true });
  const output = `// Generated by scripts/build-content.mjs - do not edit.\nexport const GUIDES = ${JSON.stringify(guides, null, 2)};\n`;
  // Only write on change: `wrangler dev` watches src/ and would otherwise rebuild in an endless loop.
  if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== output) writeFileSync(outFile, output);
  const live = guides.filter((g) => !g.draft).length;
  console.log(`Built ${guides.length} guide(s) (${live} published, ${guides.length - live} draft) -> src/generated/guides.js`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
